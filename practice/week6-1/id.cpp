#include <iostream> // 입출력 관련 기능(cout, cin 등)을 사용하기 위한 헤더 포함
#include <string>   // 문자열(string) 타입을 사용하기 위한 헤더 포함
using namespace std; // std 네임스페이스를 사용하여 std:: 생략 가능하게 함

int main() {
    string s; // 입력받은 문자열을 저장할 변수 's' 선언
    
    // 사용자에게 입력을 요청하는 안내 메시지 출력
    cout << "주민등록번호를 입력하시오: "; 
    cin >> s; // 사용자가 입력한 문자열을 변수 's'에 저장

    cout << "-가 제거된 주민등록번호: ";
    
    // 범위 기반 for 문: 문자열 s를 처음부터 끝까지 순회하며 문자를 하나씩 'c'에 담아 반복
    for (char c : s) {
        // 현재 확인 중인 문자 'c'가 하이픈('-')인지 검사
        if (c == '-') {
            continue; // '-'가 맞다면 아래의 출력 코드를 실행하지 않고 다음 문자로 넘어감
        }
        // '-'가 아닌 문자(숫자)일 경우 화면에 출력
        cout << c; 
    }
    cout << endl; // 모든 반복이 끝나면 줄바꿈(엔터) 출력

    return 0; // 프로그램 정상 종료
}